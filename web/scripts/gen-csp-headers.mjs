#!/usr/bin/env node
/**
 * gen-csp-headers.mjs — post-build step (runs after `astro build` + pagefind).
 *
 * Emits a Content-Security-Policy derived from the ACTUAL built output and wires
 * it into both deploy targets:
 *   - dist/_headers        (Netlify — merged with netlify.toml headers)
 *   - dist/vercel.json     (Vercel — CSP added to the existing /(.*) header block)
 *
 * WHY generate it (vs hand-writing the header): the site's inline <script> blocks
 * include content-derived ones (landing-page totals, the floating-question list),
 * so their SHA-256 hashes change when content changes. Computing the hashes from
 * dist/ every build keeps `script-src` strict (hash-allowlisted, NO 'unsafe-inline')
 * without anyone hand-maintaining hashes.
 *
 * POLICY design:
 *  - default-src 'self'                     same-origin only; the site loads no external origins.
 *  - script-src 'self' 'wasm-unsafe-eval' <hashes>
 *        'self'            — Astro's /_astro/*.js module scripts + dynamic imports (mermaid).
 *        'wasm-unsafe-eval'— Pagefind (search) instantiates a WebAssembly module.
 *        <sha256 hashes>   — every unique inline <script> Astro emits. NO 'unsafe-inline',
 *                            NO 'strict-dynamic' (so 'self' stays effective for /_astro/).
 *  - style-src 'self' 'unsafe-inline'       inline style="" design tokens + runtime styles
 *        (mermaid/Pagefind). Style injection is far lower risk than script injection, which
 *        stays fully locked down. Hashing styles is not viable (hundreds of inline attrs +
 *        runtime-injected styles), and a hash would make 'unsafe-inline' be ignored.
 *  - img-src 'self' data:                   favicon / inline SVG data: URIs.
 *  - font-src 'self' data:                  self-hosted Inter/JetBrains Mono + a base64
 *                                           woff2 embedded by Pagefind UI / an Astro CSS bundle.
 *  - connect-src 'self'                     quiz fetches only same-origin /questions/*.json.
 *  - worker-src 'self'                      Pagefind spins up pagefind-worker.js.
 *  - object-src 'none'; base-uri 'self'; form-action 'self'; frame-ancestors 'none'.
 *    (frame-ancestors is ineffective via <meta> but works as a real header — it's here.)
 */
import { readFile, writeFile, readdir } from "node:fs/promises";
import { existsSync } from "node:fs";
import { createHash } from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const DIST = path.resolve(__dirname, "..", "dist");

/** Recursively collect all .html files under dir. */
async function htmlFiles(dir) {
  const out = [];
  for (const ent of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, ent.name);
    if (ent.isDirectory()) out.push(...(await htmlFiles(full)));
    else if (ent.name.endsWith(".html")) out.push(full);
  }
  return out;
}

// Match inline <script> ... </script> (no src=, non-empty body).
const INLINE_SCRIPT = /<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g;

async function collectScriptHashes(files) {
  const hashes = new Set();
  for (const f of files) {
    const html = await readFile(f, "utf8");
    let m;
    while ((m = INLINE_SCRIPT.exec(html)) !== null) {
      const body = m[1];
      if (body.trim() === "") continue;
      const digest = createHash("sha256").update(body, "utf8").digest("base64");
      hashes.add(`'sha256-${digest}'`);
    }
  }
  return [...hashes].sort();
}

function buildCsp(scriptHashes) {
  const scriptSrc = ["'self'", "'wasm-unsafe-eval'", ...scriptHashes].join(" ");
  return [
    "default-src 'self'",
    `script-src ${scriptSrc}`,
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data:",
    // 'self' for the self-hosted Inter/JetBrains woff2; data: because Pagefind's
    // UI CSS and one Astro CSS bundle embed a base64 woff2 as a data: URI.
    "font-src 'self' data:",
    "connect-src 'self'",
    "worker-src 'self'",
    "manifest-src 'self'",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
    "upgrade-insecure-requests",
  ].join("; ");
}

async function main() {
  if (!existsSync(DIST)) {
    console.error("gen-csp-headers: dist/ not found — run after `astro build`.");
    process.exit(1);
  }
  const files = await htmlFiles(DIST);
  const scriptHashes = await collectScriptHashes(files);
  const csp = buildCsp(scriptHashes);

  // --- Netlify: dist/_headers (merged with netlify.toml). Path-scoped to all routes.
  const headersFile =
    `# GENERATED by scripts/gen-csp-headers.mjs — do not edit by hand.\n` +
    `# CSP is derived from the built inline scripts (${scriptHashes.length} unique hashes).\n` +
    `/*\n` +
    `  Content-Security-Policy: ${csp}\n`;
  await writeFile(path.join(DIST, "_headers"), headersFile, "utf8");

  // --- Vercel: add CSP to the existing "/(.*)" header block in dist/vercel.json.
  const vercelPath = path.join(DIST, "vercel.json");
  if (existsSync(vercelPath)) {
    const cfg = JSON.parse(await readFile(vercelPath, "utf8"));
    const block = (cfg.headers || []).find((h) => h.source === "/(.*)");
    if (block) {
      block.headers = block.headers.filter((h) => h.key !== "Content-Security-Policy");
      block.headers.push({ key: "Content-Security-Policy", value: csp });
      await writeFile(vercelPath, JSON.stringify(cfg, null, 2) + "\n", "utf8");
    } else {
      console.warn("gen-csp-headers: no '/(.*)' block in dist/vercel.json — skipped Vercel CSP.");
    }
  }

  console.log(
    `gen-csp-headers: CSP written (${scriptHashes.length} inline-script hashes) -> dist/_headers + dist/vercel.json`,
  );
}

main();
